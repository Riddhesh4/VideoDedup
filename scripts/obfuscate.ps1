#!/usr/bin/env pwsh
# Obfuscates Release DLLs with Obfuscar and swaps them into the publish output.
# Contract: publish/ exists with Release-built VideoDedup DLLs.
# This Obfuscar beta requires ABSOLUTE module paths and does not support $(Var)
# substitution, so the project file is generated here (gitignored) with resolved paths.
# Exits 1 on any failure so CI fails hard.
$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if (-not (Test-Path "$root\publish\VideoDedup.Domain.dll")) {
    Write-Error "publish/VideoDedup.Domain.dll missing. Run the Release publish steps first."
    exit 1
}

# Generate the project file with absolute paths.
$modules = @("VideoDedup.Domain", "VideoDedup.Application", "VideoDedup.Infrastructure", "VideoDedup.Workers", "VideoDedup.Desktop") |
    ForEach-Object { $dll = Join-Path $root "publish\$_.dll"; if (Test-Path $dll) { "  <Module file=`"$dll`" />" } }

$desktopBlock = ""
if (Test-Path "$root\publish\VideoDedup.Desktop.dll") {
    $desktopBlock = @"
  <Module file="$(Join-Path $root 'publish\VideoDedup.Desktop.dll')">
    <!-- WPF plumbing must keep its names: XAML/binding resolution is name-based -->
    <SkipNamespace name="VideoDedup.Desktop.*" />
  </Module>
"@
}

$xml = @"
<Obfuscator>
  <!-- Generated by scripts/obfuscate.ps1 - DO NOT EDIT; edit the script instead. -->
  <Var name="OutPath" value="$(Join-Path $root "publish-obfuscated")" />
  <Var name="KeepPublicApi" value="false" />
  <Var name="HidePrivateApi" value="true" />
  <Var name="RenameProperties" value="true" />
  <Var name="RenameFields" value="true" />
  <Var name="ReuseNames" value="false" />
  <Var name="UseUnicodeNames" value="true" />
  <Var name="HideStrings" value="true" />
  <Var name="OptimizeMethods" value="true" />

  $desktopBlock
  $modules
</Obfuscator>
"@

$xml | Set-Content "$root\obfuscar.generated.xml" -Encoding utf8

dotnet tool run obfuscar.console -- obfuscar.generated.xml
if ($LASTEXITCODE -ne 0) {
    Write-Error "Obfuscar failed with exit code $LASTEXITCODE"
    exit 1
}

# Swap obfuscated assemblies back into publish/ so the packaging step is unchanged.
Copy-Item "$root\publish-obfuscated\*" "$root\publish\" -Recurse -Force
Remove-Item "$root\publish-obfuscated" -Recurse -Force

Write-Host "Obfuscation complete."
